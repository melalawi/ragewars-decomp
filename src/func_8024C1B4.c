void func_8024C1B4(char *obj, void *anim)
{
    Event *e;
    s32 count;
    s32 i;
    Vec3 pos;

    e = func_802625B8(anim);
    count = func_802625E4(anim);
    for (i = 0; i < count; i++) {
        switch (e[i].effect) {
        case 6:
        case 7:
            func_80272908(obj + 0x74, &e[i].local, &pos);
            func_80265E30(obj, obj, e[i].effect, -1, pos, e[i].params);
        }
    }
}

