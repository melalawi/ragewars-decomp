#ifndef RAGEWARS_BASETYPES_H
#define RAGEWARS_BASETYPES_H

/* The scalar type names this project's C is written in.  The widths are the
 * ones this cartridge's ABI fixes: int is 32 bits, long long is 64.
 */

typedef signed char s8;
typedef unsigned char u8;
typedef short s16;
typedef unsigned short u16;
typedef int s32;
typedef unsigned int u32;
typedef long long s64;
typedef unsigned long long u64;
typedef float f32;
typedef double f64;

#endif
