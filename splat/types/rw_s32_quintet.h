#ifndef RAGEWARS_RW_S32_QUINTET_H
#define RAGEWARS_RW_S32_QUINTET_H

/* Five signed words, recovered independently in 4 landed files. */
typedef struct RWS32Quintet {
    /* 0x00 */ s32 word_00;
    /* 0x04 */ s32 word_04;
    /* 0x08 */ s32 word_08;
    /* 0x0C */ s32 word_0C;
    /* 0x10 */ s32 word_10;
} RWS32Quintet;

#endif
